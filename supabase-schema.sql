  values (p_member_id, v_room_id, v_name);
  return true;
end;
$$;

create or replace function public.get_songbattle_room_state(
  p_room_code text,
  p_member_id uuid,
  p_host_token uuid default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_room public.songbattle_rooms%rowtype;
  v_is_host boolean;
  v_result jsonb;
begin
  select * into v_room from public.songbattle_rooms
  where room_code = upper(btrim(p_room_code)) and is_active;
  if not found then raise exception 'Room not found'; end if;

  v_is_host := coalesce(
    v_room.host_member_id = p_member_id and v_room.host_token = p_host_token,
    false
  );
  if not v_is_host and not exists (
    select 1 from public.songbattle_room_members
    where room_id = v_room.id and member_id = p_member_id
  ) then raise exception 'You are not a member of this room'; end if;
  if exists (
    select 1 from public.songbattle_room_bans
    where room_id = v_room.id and member_id = p_member_id
  ) then raise exception 'You were kicked from this room'; end if;

  select jsonb_build_object(
    'room', jsonb_build_object('code', v_room.room_code, 'created_at', v_room.created_at),
    'is_host', v_is_host,
    'members', case when v_is_host then
      coalesce((
        select jsonb_agg(jsonb_build_object(
          'id', m.member_id,
          'display_name', m.display_name,
          'is_host', m.member_id = v_room.host_member_id
        ) order by m.joined_at)
        from public.songbattle_room_members as m where m.room_id = v_room.id
      ), '[]'::jsonb)
      else jsonb_build_array(jsonb_build_object(
        'id', p_member_id,
        'display_name', (select m.display_name from public.songbattle_room_members as m
          where m.room_id = v_room.id and m.member_id = p_member_id),
        'is_host', false
      ))
    end,
    'submissions', case when v_is_host then
      coalesce((
        select jsonb_agg(jsonb_build_object(
          'id', s.id, 'member_id', s.member_id, 'member_name', m.display_name,
          'title', s.title, 'url', s.url,
          'provider', case when s.url ~* '^https://open\.spotify\.com/' then 'spotify' else 'youtube' end,
          'created_at', s.created_at
        ) order by s.created_at desc)
        from public.songbattle_room_submissions as s
        join public.songbattle_room_members as m on m.member_id = s.member_id
        where s.room_id = v_room.id
      ), '[]'::jsonb)
      else coalesce((
        select jsonb_agg(jsonb_build_object(
          'id', s.id, 'member_id', s.member_id, 'member_name', m.display_name,
          'title', s.title, 'url', s.url,
          'provider', case when s.url ~* '^https://open\.spotify\.com/' then 'spotify' else 'youtube' end,
          'created_at', s.created_at
        ) order by s.created_at desc)
        from public.songbattle_room_submissions as s
        join public.songbattle_room_members as m on m.member_id = s.member_id
        where s.room_id = v_room.id and s.member_id = p_member_id
      ), '[]'::jsonb)
    end
  ) into v_result;

  v_result := v_result || jsonb_build_object(
    'status', v_room.status,
    'current_round', v_room.current_round,
    'total_rounds', v_room.total_rounds,
    'matches', case when v_room.status = 'battle' then coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', mt.id,
        'slot', mt.slot,
        'a', public.songbattle_song_json(mt.sub_a),
        'b', public.songbattle_song_json(mt.sub_b),
        'votes_a', (select count(*) from public.songbattle_room_votes v where v.match_id = mt.id and v.choice = 0),
        'votes_b', (select count(*) from public.songbattle_room_votes v where v.match_id = mt.id and v.choice = 1),
        'my_choice', (select v.choice from public.songbattle_room_votes v where v.match_id = mt.id and v.member_id = p_member_id),
        'decided', mt.winner_id is not null
      ) order by mt.slot)
      from public.songbattle_room_matches mt
      where mt.id = (
        select m2.id from public.songbattle_room_matches m2
        where m2.room_id = v_room.id and m2.round = v_room.current_round and m2.winner_id is null
        order by m2.slot limit 1
      )
    ), '[]'::jsonb) else '[]'::jsonb end,
    'match_number', (select count(*) + 1 from public.songbattle_room_matches mt
      where mt.room_id = v_room.id and mt.round = v_room.current_round
        and mt.sub_b is not null and mt.winner_id is not null),
    'match_total', (select count(*) from public.songbattle_room_matches mt
      where mt.room_id = v_room.id and mt.round = v_room.current_round and mt.sub_b is not null),
    'last_result', (
      select jsonb_build_object(
        'id', mt.id,
        'round', mt.round,
        'a', public.songbattle_song_json(mt.sub_a),
        'b', public.songbattle_song_json(mt.sub_b),
        'votes_a', (select count(*) from public.songbattle_room_votes v where v.match_id = mt.id and v.choice = 0),
        'votes_b', (select count(*) from public.songbattle_room_votes v where v.match_id = mt.id and v.choice = 1),
        'winner_id', mt.winner_id
      )
      from public.songbattle_room_matches mt
      where mt.room_id = v_room.id and mt.sub_b is not null and mt.winner_id is not null
      order by mt.decided_at desc limit 1
    ),
    'champion', case when v_room.status = 'finished' then (
      select public.songbattle_song_json(mt.winner_id)
      from public.songbattle_room_matches mt
      where mt.room_id = v_room.id and mt.round = v_room.current_round limit 1
    ) else null end,
    'leaderboard', case when v_room.status = 'finished' then coalesce((
      select jsonb_agg(jsonb_build_object(
        'member_name', m.display_name, 'votes', t.votes, 'songs', t.songs
      ) order by t.votes desc, m.display_name)
      from (
        select ps.member_id, sum(ps.cnt) as votes, count(*) as songs
        from (
          select s.member_id, (
            select count(*) from public.songbattle_room_votes v
            join public.songbattle_room_matches mt on mt.id = v.match_id
            where mt.room_id = v_room.id
              and ((v.choice = 0 and mt.sub_a = s.id) or (v.choice = 1 and mt.sub_b = s.id))
          ) as cnt
          from public.songbattle_room_submissions s where s.room_id = v_room.id
        ) ps group by ps.member_id
      ) t join public.songbattle_room_members m on m.member_id = t.member_id
    ), '[]'::jsonb) else '[]'::jsonb end
  );
  return v_result;
end;
$$;

create or replace function public.submit_songbattle_room_song(
  p_room_code text,
  p_member_id uuid,
  p_title text,
  p_url text
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_room_id uuid;
  v_title text := btrim(coalesce(p_title, ''));
  v_url text := btrim(p_url);
  v_submission_id uuid;
begin
  select id into v_room_id from public.songbattle_rooms
  where room_code = upper(btrim(p_room_code)) and is_active;
  if v_room_id is null then raise exception 'Room not found'; end if;
  if not exists (
    select 1 from public.songbattle_room_members
    where room_id = v_room_id and member_id = p_member_id
  ) or exists (
    select 1 from public.songbattle_room_bans
    where room_id = v_room_id and member_id = p_member_id
  ) then raise exception 'You are not a member of this room'; end if;
  if (select status from public.songbattle_rooms where id = v_room_id) <> 'lobby' then
    raise exception 'A battle már elindult, most nem küldhető be új zene.';
  end if;
  if length(v_title) > 120 or length(v_url) > 500
    or v_url !~* '^https://(youtube\.com/|www\.youtube\.com/|music\.youtube\.com/|youtu\.be/|open\.spotify\.com/)'
  then raise exception 'Invalid Spotify or YouTube URL'; end if;

  insert into public.songbattle_room_submissions (room_id, member_id, title, url)
  values (v_room_id, p_member_id, v_title, v_url)
  returning id into v_submission_id;
  return v_submission_id;
end;
$$;

