create or replace function public.songbattle_create_round(p_room_id uuid, p_round integer, p_ids uuid[])
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_len integer := array_length(p_ids, 1);
begin
  for i in 1..ceil(v_len / 2.0)::integer loop
    insert into public.songbattle_room_matches (room_id, round, slot, sub_a, sub_b, winner_id, decided_at)
    values (p_room_id, p_round, i, p_ids[2 * i - 1], p_ids[2 * i],
      case when 2 * i > v_len then p_ids[2 * i - 1] end,
      case when 2 * i > v_len then clock_timestamp() end);
  end loop;
end;
$$;

create or replace function public.songbattle_advance(p_room_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_room public.songbattle_rooms%rowtype;
  v_ids uuid[];
begin
  loop
    select * into v_room from public.songbattle_rooms where id = p_room_id;
    if exists (
      select 1 from public.songbattle_room_matches
      where room_id = p_room_id and round = v_room.current_round and winner_id is null
    ) then return; end if;

    select array_agg(winner_id order by slot) into v_ids
    from public.songbattle_room_matches
    where room_id = p_room_id and round = v_room.current_round;

    if array_length(v_ids, 1) = 1 then
      update public.songbattle_rooms set status = 'finished' where id = p_room_id;
      return;
    end if;
    update public.songbattle_rooms set current_round = current_round + 1 where id = p_room_id;
    perform public.songbattle_create_round(p_room_id, v_room.current_round + 1, v_ids);
  end loop;
end;
$$;

create or replace function public.create_songbattle_room(
  p_member_id uuid,
  p_display_name text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_room_id uuid := gen_random_uuid();
  v_room_code text;
  v_host_token uuid := gen_random_uuid();
  v_name text := btrim(p_display_name);
begin
  if p_member_id is null or v_name is null or length(v_name) not between 1 and 32 then
    raise exception 'A név 1 és 32 karakter közötti legyen.';
  end if;

  for attempt in 1..10 loop
    v_room_code := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6));
    begin
      insert into public.songbattle_rooms (id, room_code, host_member_id, host_token)
      values (v_room_id, v_room_code, p_member_id, v_host_token);
      exit;
    exception when unique_violation then
      if attempt = 10 then
        raise exception 'Nem sikerült egyedi szobakódot létrehozni.';
      end if;
    end;
  end loop;

  insert into public.songbattle_room_members (member_id, room_id, display_name)
  values (p_member_id, v_room_id, v_name);

  return jsonb_build_object('room_code', v_room_code, 'host_token', v_host_token);
end;
$$;

create or replace function public.join_songbattle_room(
  p_room_code text,
  p_member_id uuid,
  p_display_name text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_room_id uuid;
  v_name text := btrim(p_display_name);
begin
  if p_member_id is null or v_name is null or length(v_name) not between 1 and 32 then
    raise exception 'A név 1 és 32 karakter közötti legyen.';
